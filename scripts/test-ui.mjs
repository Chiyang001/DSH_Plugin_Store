import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || undefined });
const page = await browser.newPage({ viewport: { width: 1440, height: 1120 }, deviceScaleFactor: 1 });
const errors = []; page.on('pageerror', error => errors.push(error.message));
await mkdir('test-results', { recursive: true });
const address = process.env.STORE_URL || 'http://127.0.0.1:5173';
try {
  await page.goto(address);
  await page.getByRole('heading', { name: '发现插件.' }).waitFor();
  assert.equal(await page.getByRole('link', { name: '访问炽阳001的B站主页' }).getAttribute('href'), 'https://space.bilibili.com/404891612');
  assert.equal(await page.locator('.store-footer').innerText().then(text => text.includes('由炽阳001构建')), false);
  await page.screenshot({ path: 'test-results/store-light.png', fullPage: true, animations: 'disabled' });
  assert.ok(await page.locator('.store-card').count() > 5);
  await page.locator('.store-card').first().getByRole('button', { name: '收藏', exact: false }).click();
  await page.getByRole('button', { name: '我的收藏', exact: false }).first().click();
  assert.equal(await page.locator('.store-card').count(), 1);
  await page.reload();
  await page.getByRole('button', { name: '我的收藏', exact: false }).first().click();
  assert.equal(await page.locator('.store-card').count(), 1);
  await page.getByRole('button', { name: '切换深色主题' }).click();
  await page.getByRole('button', { name: '发现', exact: true }).click();
  await page.screenshot({ path: 'test-results/store-dark.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: '知识与记忆', exact: false }).first().click();
  assert.ok(await page.locator('.store-card').count() > 0);
  await page.getByRole('textbox', { name: '搜索插件' }).fill('this-plugin-does-not-exist');
  await page.getByRole('heading', { name: '暂时没有匹配的插件' }).waitFor();
  await page.getByRole('button', { name: '已安装', exact: true }).click();
  await page.getByRole('heading', { name: '你的工具箱，准备就绪' }).waitFor();
  await page.getByRole('button', { name: '插件源', exact: false }).first().click();
  await page.getByRole('button', { name: '添加订阅源' }).click();
  await page.getByRole('heading', { name: '连接新的插件源' }).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: '发现', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '切换浅色主题' }).click();
  await page.screenshot({ path: 'test-results/store-mobile.png', fullPage: true, animations: 'disabled' });
  await page.locator('.store-mobile-nav').getByRole('button', { name: '更多', exact: false }).click();
  await page.locator('dialog').getByRole('link', { name: '访问炽阳001的B站主页' }).waitFor({ state: 'visible' });
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.equal(await page.locator('.store-main').evaluate(e => e.scrollWidth > e.clientWidth + 1), false);
  await page.close();

  const host = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  host.on('pageerror', error => errors.push(error.message));
  await host.route(/\/src\/preview\.tsx(?:\?.*)?$/, route => route.fulfill({ contentType: 'application/javascript', body: "import '/tests/fixture.tsx';" }));
  await host.goto(address);
  await host.getByRole('button', { name: '已安装', exact: false }).first().click();
  await host.getByRole('heading', { name: '测试开发工具' }).waitFor();
  await host.locator('.store-installed-row').filter({ hasText: '测试开发工具' }).getByRole('button', { name: '已启用' }).click();
  await host.getByRole('status').filter({ hasText: '重启 DeepSeek Harness' }).waitFor();
  assert.deepEqual((await host.evaluate(() => window.__storeCalls)).find(c => c[0] === 'toggle'), ['toggle', 'dsh-test-tools', false]);
  await host.getByRole('button', { name: '卸载 测试开发工具' }).click();
  assert.equal((await host.evaluate(() => window.__storeCalls)).filter(c => c[0] === 'remove').length, 0);
  await host.getByRole('button', { name: '确认卸载' }).click();
  await host.getByRole('alert').filter({ hasText: '卸载被测试宿主拒绝' }).waitFor();
  assert.equal(await host.locator('dialog').isVisible(), true);
  await host.getByRole('button', { name: '关闭弹窗' }).click();
  await host.getByRole('button', { name: '检查更新' }).click();
  await host.getByRole('button', { name: '确认更新' }).click();
  await host.getByRole('status').filter({ hasText: '重启 DeepSeek Harness' }).waitFor();
  assert.ok((await host.evaluate(() => window.__storeCalls)).some(c => c[0] === 'update' && c[2] === '1.1.0'));
  await host.getByRole('button', { name: '发现', exact: true }).click();
  await host.locator('.store-card').filter({ hasText: 'GitHub 社区' }).first().getByRole('button', { name: '安装', exact: true }).click();
  assert.equal((await host.evaluate(() => window.__storeCalls)).filter(c => c[0] === 'install').length, 0);
  await host.getByRole('button', { name: '确认安装' }).click();
  await host.getByRole('status').filter({ hasText: '重启 DeepSeek Harness' }).waitFor();
  const trace = await host.evaluate(() => window.__storeCalls);
  assert.ok(trace.some(c => c[0] === 'inspect')); assert.ok(trace.some(c => c[0] === 'install'));
  await host.getByRole('button', { name: '插件源', exact: false }).first().click();
  await host.route('https://store-test.example/index.json', route => route.fulfill({ json: { format: 1, title: '测试目录', plugins: [{ name: 'dsh-from-source', title: '源里的测试插件', versions: [{ version: '1.0.0', source: { type: 'npm' } }] }] }, headers: { 'Access-Control-Allow-Origin': '*' } }));
  await host.getByRole('button', { name: '添加订阅源' }).click();
  await host.getByRole('textbox', { name: '源名称' }).fill('测试订阅');
  await host.getByRole('textbox', { name: '索引地址' }).fill('https://store-test.example/index.json');
  await host.getByRole('button', { name: '连接订阅源' }).click();
  await host.getByRole('heading', { name: '测试订阅' }).waitFor();
  await host.getByRole('button', { name: '发现', exact: true }).click();
  await host.getByRole('textbox', { name: '搜索插件' }).fill('源里的测试插件');
  await host.getByRole('heading', { name: '源里的测试插件' }).waitFor();
  await host.close();
  assert.deepEqual(errors, []);
  console.log('UI passed: responsive layouts, themes, search, categories, persistent favorites, source subscription, install confirmation, enable/disable, update, failure and restart results.');
} catch (error) { for (const active of browser.contexts().flatMap(context => context.pages())) { if (!active.isClosed()) { await active.screenshot({ path: 'test-results/ui-error.png' }); console.log((await active.locator('body').innerText()).slice(0, 1600)); } } if (errors.length) console.log(errors); throw error; }
finally { await browser.close(); }
